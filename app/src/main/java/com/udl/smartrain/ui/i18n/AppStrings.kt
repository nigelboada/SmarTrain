fun AppLanguage.text(key: TextKey): String {
    return strings(this).getValue(key)
}

fun AppLanguage.text(key: TextKey, vararg args: Any): String {
    return text(key).format(*args)
}

fun AppLanguage.activityLabel(label: String): String {
    return when (label) {
        "Desplacament suau" -> text(TextKey.ACTIVITY_LIGHT_MOVEMENT)
        "Alta intensitat" -> text(TextKey.ACTIVITY_HIGH_INTENSITY)
        "Repos" -> text(TextKey.ACTIVITY_REST)
        "Caminar" -> text(TextKey.MODEL_WALKING)
        "Pujar escales" -> text(TextKey.MODEL_UPSTAIRS)
        "Baixar escales" -> text(TextKey.MODEL_DOWNSTAIRS)
        "Seure" -> text(TextKey.MODEL_SITTING)
        "Dret" -> text(TextKey.MODEL_STANDING)
        "Estirat" -> text(TextKey.MODEL_LAYING)
        "Desconeguda" -> text(TextKey.UNKNOWN)
        else -> label
    }
}

private fun strings(language: AppLanguage): Map<TextKey, String> {
    return when (language) {
        AppLanguage.CATALAN -> catalan
        AppLanguage.ENGLISH -> english
        AppLanguage.SPANISH -> spanish
        AppLanguage.CHINESE -> chinese
    }
}

